from ozet_data import MODULES as _OLD  # noqa: E402


def _voc(must, rec, newpage=False):
    return dict(kind="voc", newpage=newpage, title=f"{len(must) + len(rec)} kelime", small="◦ işaretliler: öğrenmen tavsiye edilir",
                intro="Okunuşlar yaklaşıktır: « ⁿ » genizden söylenen sesi gösterir. Doğru telaffuz için kelimeleri sitede sesli dinle.",
                words=[(w, o, t, False) for w, o, t in must] + [(w, o, t, True) for w, o, t in rec])


def _delf(n):
    d = _OLD[n]["delf"]
    return dict(kind="points", title="DELF köşesi", small=d["title"], points=d["points"], key=d["key"], key_tr=d["key_tr"])


def _old_voc(n, newpage=False):
    return _voc(_OLD[n]["voc_must"], _OLD[n]["voc_rec"], newpage)


